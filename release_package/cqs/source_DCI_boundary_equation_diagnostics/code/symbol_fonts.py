def table(font: str | None) -> dict | None:
    """글꼴 이름(양끝 빈칸 · 대소문자 무시)의 대응표. 대응표가 없는 글꼴은 None."""
    return TABLES.get(font.strip().lower()) if font else None


def glyph(tab: dict, code: int) -> str | None:
    """자리 번호(0x20~0xFF, 또는 사용자 영역 0xF020~0xF0FF)의 유니코드 글자. 대응표에 없으면 None."""
    if 0xF020 <= code <= 0xF0FF:
        code -= 0xF000
    elif code > 0xFF:
        return None
    u = tab.get(code)
    return chr(u) if u is not None else None


def sym_text(sym) -> str:
    """`w:sym` 의 글자. 글꼴이나 부호가 대응표에 없으면 빈 글."""
    tab = table(sym.get(_FONT))
    try:
        code = int(sym.get(_CHAR) or "", 16)
    except ValueError:
        return ""
    return (glyph(tab, code) or "") if tab else ""


def font_aliases(font_table) -> dict[str, str]:
    """글꼴 표(`word/fontTable.xml` 의 lxml 트리) 가운데 대응표가 없는 글꼴의 이름(양끝 빈칸을 떼고 소문자) →
    그 글꼴의 대체 이름이 가리키는, 대응표가 있는 글꼴 이름.

    글꼴 표의 `w:font/w:altName` 은 글꼴을 찾지 못할 때 대신 찾는 이름이다(ISO/IEC 29500-1 §17.8.3.1 "a set of
    alternative names which can be used to locate the font specified by the parent element"). Word 는 이 값을 나누지
    않고 한 이름으로 다루며, 찾지 못한 글꼴을 다른 글꼴로 정하면 그 글꼴 이름을 이 자리에 적는다([MS-OI29500]
    Part 1 §17.8.3.1 d. "When Word resolves an unknown font, it changes the value of the altName element to the font
    to which it was resolved"). 그래서 대응표가 없는 글꼴의 대체 이름이 대응표 있는 기호 글꼴이면, 그 글자는 그
    기호 글꼴로 그려졌다. 코퍼스의 Mathematica1 이 이 꼴이다(대체 이름 Symbol · `w:charset` 02). 38.101-1 부속서의
    PRACH EVM 창 표는 `w:sym` Mathematica1 F0D7 · F06D 로 `288⋅2^-μ` 를 적는다(`2^-` 는 위첨자) — 대응표 없이 읽으면
    `2882-` 로 μ 가 사라진다. 대체 이름이 없거나 대응표가 없는 이름이면 넣지 않는다(무엇으로 그렸는지 모른다).
    """
    out: dict[str, str] = {}
    if font_table is None:
        return out
    for f in font_table.iter(W + "font"):
        name = f.get(_NAME_ATTR)
        alt = f.find(_ALT_NAME)
        if not name or alt is None or table(name):
            continue
        sub = alt.get(_VAL)
        if table(sub):
            out[name.strip().lower()] = sub
    return out


